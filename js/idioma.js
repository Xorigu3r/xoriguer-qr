function T(s, v) {
  let r = IX >= 0 && F[s] ? F[s][IX] : s;
  if (v) r = r.replace(/\{(\w+)\}/g, (m, k) => (k in v ? v[k] : m));
  return r;
}

function tradueix(arrel) {
  if (IX < 0) return;
  arrel.querySelectorAll('[data-t]').forEach(e => { const h = H[e.dataset.t]; if (h) e.innerHTML = h[IX]; });
  const w = document.createTreeWalker(arrel, NodeFilter.SHOW_TEXT, {
    acceptNode: n => (n.parentElement.closest('script,style,svg,[data-t]') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT) });
  for (let n; (n = w.nextNode());) {
    const t = n.nodeValue.trim();
    if (t && F[t]) n.nodeValue = n.nodeValue.replace(t, F[t][IX]);
  }
  arrel.querySelectorAll('[placeholder],[title],[aria-label]').forEach(e => {
    for (const a of ['placeholder', 'title', 'aria-label']) {
      const t = e.getAttribute(a);
      if (t && F[t]) e.setAttribute(a, F[t][IX]);
    }
  });
}

